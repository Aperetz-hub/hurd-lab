/*
 * hurd-mig-sys -- raw FFI to the GNU Mach / MIG interface.
 *
 * What this crate is:
 *   - `#![no_std]` by construction. It is meant to be linked into a Hurd
 *     translator or into a freestanding component, where `std` does not exist.
 *   - A *thin* layer. The generated bindings are included verbatim so struct
 *     layouts are the compiler's business, and hand-written helpers live on top
 *     rather than around them.
 *
 * What this crate is NOT:
 *   - Not a safe Mach binding. Everything crossing the FFI boundary is `unsafe`
 *     and stays that way; the point of the safe-systems work is to grow a
 *     checked layer above this one, one call at a time.
 *
 * Cargo feature `alloc-support` exposes allocation hooks. See the `alloc`
 * module: on Hurd the allocator is the translator's, so a `#![no_std]` binary
 * needs a `#[global_allocator]` that forwards to `malloc`/`free`.
 */

#![no_std]
#![deny(missing_docs)]

// Generated by build.rs. Kept as a module (not a crate root) so the allow-list
// inside it cannot relax *our* lints.
mod raw {
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

pub use raw::*;

/* ---------------------------------------------------------------------- */
/* Hand-written layer                                                     */
/* ---------------------------------------------------------------------- */

/// Return value of every Mach entry point.
///
/// Mach uses a small, closed set of numeric codes; anything else means the
/// callee was not reached at all.
pub type Krn = kern_return_t;

/// `true` for [`KERN_SUCCESS`].
#[inline]
pub const fn is_ok(kr: Krn) -> bool {
    kr == KERN_SUCCESS
}

/// Human-readable text for a Mach error code.
///
/// # Safety
///
/// `buffer` must be valid for `len` bytes; the C side writes into it
/// unconditionally.
pub unsafe fn error_string(kr: Krn, buffer: &mut [core::ffi::c_char]) -> &str {
    // mach_error_string() returns a string that may be longer than `buffer`;
    // it truncates rather than failing, so we clamp to what we own.
    let max = buffer.len();
    if max == 0 {
        return "";
    }
    // SAFETY: caller guarantees the slice is valid for `max` bytes.
    unsafe { raw::mach_error_string(kr, buffer.as_mut_ptr(), max as raw::mach_msg_size_t) };
    // SAFETY: mach_error_string() NUL-terminates on success.
    unsafe { core::ffi::CStr::from_ptr(buffer.as_ptr()) }
        .to_str()
        .unwrap_or("<non-UTF-8 error string>")
}

/// The task port of the calling task, obtained from the Mach runtime.
///
/// # Safety
///
/// Must be called from a thread that is actually part of a task, i.e. not
/// before Mach has set up the calling thread.
pub unsafe fn task_self() -> mach_port_t {
    // SAFETY: caller guarantees a live Mach thread.
    unsafe { raw::mach_task_self() }
}

/// Allocate a fresh receive right in the calling task.
///
/// # Safety
///
/// `port` must point to writable storage for a `mach_port_t`. On success the
/// name is a receive right the caller owns and must eventually deallocate.
pub unsafe fn allocate_receive_right(port: *mut mach_port_t) -> Krn {
    // SAFETY: caller guarantees `port` is writable.
    unsafe { raw::mach_port_allocate(raw::mach_task_self(), raw::MACH_MSG_TYPE_COPY_RECEIVE, port) }
}

/// Allocate `count` bytes of zeroed memory in the calling task's address space.
///
/// This is the allocator Hurd translators actually use; see [`alloc`].
///
/// # Safety
///
/// `address` must point to writable storage for a `vm_offset_t`.
pub unsafe fn vm_allocate(address: *mut vm_offset_t, count: usize) -> Krn {
    // SAFETY: caller guarantees `address` is writable; `count` fits in
    // vm_size_t on this target (both are 64-bit).
    unsafe { raw::mig_allocate(raw::mach_task_self(), count as raw::vm_size_t, address) }
}

/// Release memory obtained from [`vm_allocate`].
///
/// # Safety
///
/// `address` must be a live allocation of exactly `count` bytes from
/// [`vm_allocate`] and must not be used afterwards.
pub unsafe fn vm_deallocate(address: vm_offset_t, count: usize) -> Krn {
    // SAFETY: caller guarantees the allocation is live and owned here.
    unsafe { raw::mig_deallocate(raw::mach_task_self(), address, count as raw::vm_size_t) }
}

